// Usage: node build-tokens.mjs
// Reads tokens.json (Figma variable export, DTCG style) and writes tokens.css.
// Semantic tokens become var() aliases of primitives, so the two Figma tiers survive in CSS.
import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync(new URL("./tokens.json", import.meta.url), "utf8"));
const PREFIX = "--gt-";

const cssName = (path) => {
  const segs = path.filter((s, i) => !(i === 0) && s !== "color");
  return PREFIX + segs.join("-");
};

const refToVar = (value) =>
  value.replace(/\{([^}]+)\}/g, (_, p) => `var(${cssName(p.split("."))})`);

const lines = [];
const walk = (node, path, tier) => {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (val && typeof val === "object" && "$value" in val) {
      const name = cssName([...path, key]);
      const note = val.$description ? ` /* ${val.$description} */` : "";
      lines.push(`  ${name}: ${refToVar(String(val.$value))};${note}`);
    } else if (val && typeof val === "object") {
      walk(val, [...path, key], tier);
    }
  }
};

const sections = [
  ["primitive", "Primitives: raw values. Do not use in components."],
  ["semantic", "Semantic: roles. Use these in components."],
  ["proposed", "Proposed: used in code or hardcoded in Figma, no Figma variable yet."],
];
let out = `/* GENERATED by build-tokens.mjs from tokens.json. Do not edit by hand. */\n.giatec-portal {\n`;
for (const [tier, title] of sections) {
  lines.length = 0;
  walk(tokens[tier], [tier], tier);
  out += `  /* ${title} */\n${lines.join("\n")}\n\n`;
}
out = out.trimEnd() + "\n}\n";
writeFileSync(new URL("./tokens.css", import.meta.url), out);
console.log(`tokens.css written, ${out.split("\n").filter((l) => l.includes(": ")).length} declarations`);
